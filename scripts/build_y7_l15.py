def px2pt(text):
    """1pt = 2px on a 1920x1080 projector, so every px value halves into pt.
    Applied to the stylesheet and to the emitted slides, which is why the
    lesson content below is still written in px — one rule, one place.

    Safe across the SVG drawings: their coordinates, viewBox and stroke
    widths are unitless user units and carry no 'px' to match."""
    def one(m):
        v = float(m.group(1)) / 2
        return ('%g' % v) + 'pt'
    return re.sub(r'(-?\d*\.?\d+)px', one, text)


